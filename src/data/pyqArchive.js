/**
 * Parses a student's numerical answer string safely (handles commas, units, decimals).
 */
export function parseNumericalInput(raw) {
  const cleaned = String(raw ?? '')
    .replace(/,/g, '')
    .replace(/[₹$]/g, '')
    .trim()
  const match = cleaned.match(/-?\d+(\.\d+)?/)
  if (!match) return null
  const val = Number(match[0])
  return Number.isFinite(val) ? val : null
}

/**
 * Validates either an MCQ option pick or a typed numerical input against a PYQ record.
 */
export function validateArchiveAnswer(question, { optionIndex = null, numericInput = '' }) {
  if (!question) return { validInput: false, correct: false }

  if (question.questionType === 'numerical' && String(numericInput).trim() !== '') {
    const parsed = parseNumericalInput(numericInput)
    if (parsed === null || !Number.isFinite(question.numericAnswer)) {
      return { validInput: false, correct: false }
    }
    const tol = Math.max(0.05, Math.abs(question.numericAnswer) * 0.015)
    return {
      validInput: true,
      correct: Math.abs(parsed - question.numericAnswer) <= tol,
      expectedDisplay: question.options[question.correctIndex],
    }
  }

  if (Number.isInteger(optionIndex) && optionIndex >= 0 && optionIndex < question.options.length) {
    return {
      validInput: true,
      correct: optionIndex === question.correctIndex,
      expectedDisplay: question.options[question.correctIndex],
    }
  }

  return { validInput: false, correct: false }
}

/**
 * Filters Mensuration PYQ Archive records across collection, keyword, year, exam, topic, difficulty & type.
 */
export function filterArchiveQuestions({
  collection = 'all', // 'all' | 'verified_pyq' | 'pyq_style_practice'
  query = '',
  exam = 'all',
  topic = 'all',
  difficulty = 'all',
  questionType = 'all',
  year = 'all',
} = {}) {
  const qLower = String(query ?? '').trim().toLowerCase()
  const yearNum = year !== 'all' ? Number(year) : null

  return ALL_ARCHIVE_QUESTIONS.filter((item) => {
    if (collection !== 'all' && item.authenticity !== collection) return false
    if (exam !== 'all' && item.exam !== exam) return false
    if (topic !== 'all' && item.topic !== topic) return false
    if (difficulty !== 'all' && item.difficulty !== difficulty) return false
    if (questionType !== 'all' && item.questionType !== questionType) return false
    if (yearNum !== null && item.year !== yearNum) return false
    if (qLower) {
      const hay = `${item.question} ${item.exam} ${item.topic} ${item.year ?? ''} ${item.paperSession ?? ''} ${item.formulaUsed}`.toLowerCase()
      if (!hay.includes(qLower)) return false
    }
    return true
  })
}

/**
 * Computes transparent frequency intelligence distinguishing strictly Verified PYQs
 * from PYQ-Style Practice without ever confusing missing historical papers with 0 real questions.
 */
export function computeArchiveFrequencyStats(scope = 'verified_pyq') {
  const sourceList =
    scope === 'verified_pyq'
      ? VERIFIED_PYQS
      : scope === 'pyq_style_practice'
        ? PYQ_STYLE_PRACTICE
        : ALL_ARCHIVE_QUESTIONS

  const byYearMap = new Map()
  for (let y = ARCHIVE_START_YEAR; y <= ARCHIVE_END_YEAR; y += 1) {
    byYearMap.set(y, 0)
  }
  const byExam = Object.fromEntries(PYQ_EXAMS.map((e) => [e, 0]))
  const byTopic = Object.fromEntries(PYQ_TOPICS.map((t) => [t, 0]))
  const byDifficulty = Object.fromEntries(PYQ_DIFFICULTIES.map((d) => [d, 0]))
  const topicByExam = Object.fromEntries(
    PYQ_TOPICS.map((t) => [t, Object.fromEntries(PYQ_EXAMS.map((e) => [e, 0]))]),
  )

  for (const q of sourceList) {
    if (Number.isInteger(q.year) && byYearMap.has(q.year)) {
      byYearMap.set(q.year, byYearMap.get(q.year) + 1)
    }
    if (byExam[q.exam] !== undefined) byExam[q.exam] += 1
    if (byTopic[q.topic] !== undefined) byTopic[q.topic] += 1
    if (byDifficulty[q.difficulty] !== undefined) byDifficulty[q.difficulty] += 1
    if (topicByExam[q.topic]?.[q.exam] !== undefined) {
      topicByExam[q.topic][q.exam] += 1
    }
  }

  const byYear = Array.from(byYearMap.entries()).map(([year, count]) => ({
    year,
    count,
    verifiedIndexed: count > 0,
  }))

  const rankedTopics = [...PYQ_TOPICS]
    .map((topic) => ({ topic, count: byTopic[topic] }))
    .sort((a, b) => b.count - a.count)

  const verifiedYearsPresent = byYear
    .filter((entry) => entry.verifiedIndexed)
    .map((entry) => entry.year)
  const missingVerifiedYears = byYear
    .filter((entry) => !entry.verifiedIndexed)
    .map((entry) => entry.year)

  return {
    scope,
    totalInScope: sourceList.length,
    verifiedCount: VERIFIED_PYQS.length,
    stylePracticeCount: PYQ_STYLE_PRACTICE.length,
    totalArchiveCount: ALL_ARCHIVE_QUESTIONS.length,
    byYear,
    byExam,
    byTopic,
    byDifficulty,
    topicByExam,
    rankedTopics,
    verifiedYearsPresent,
    missingVerifiedYears,
  }
}
